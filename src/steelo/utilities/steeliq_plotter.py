    def _overlay_production_lines(self, ax, production_df: Optional[pd.DataFrame]) -> list[Line2D]:
        """Draw iron and steel total production as lines on a secondary y-axis.

        Lines use a bright fill colour with a thicker black halo (via path effects) so
        they stay legible against any combination of stacked-area background colours.
        Returns legend proxies so the caller can append them to the main legend; a
        secondary-axis legend would otherwise sit alone in the corner.

        Args:
            ax: Primary emissions axis.
            production_df: Year-indexed Mt frame with at least one of {"iron", "steel"} columns.

        Returns:
            List of Line2D proxies (empty when no overlay was drawn).
        """
        if production_df is None or production_df.empty:
            return []

        ax2 = ax.twinx()
        ax2.set_ylabel("Total Production (Mt)", fontsize=12, color="black")
        product_styles = {
            "iron": {"color": "#FFD700", "label": "iron"},
            "steel": {"color": "#FFFFFF", "label": "steel"},
        }
        halo = [path_effects.Stroke(linewidth=2.5, foreground="black"), path_effects.Normal()]
        proxies: list[Line2D] = []
        for product, style in product_styles.items():
            if product not in production_df.columns:
                continue
            series = production_df[product].sort_index()
            ax2.plot(
                series.index,
                series.values,
                color=style["color"],
                linewidth=1.1,
                linestyle="-",
                path_effects=halo,
                label=style["label"],
            )
            proxies.append(
                Line2D(
                    [0],
                    [0],
                    color=style["color"],
                    linewidth=1.1,
                    linestyle="-",
                    path_effects=halo,
                    label=style["label"],
                )
            )

        ax2.set_ylim(bottom=0)
        return proxies

    @staticmethod
    def _legend_order_for_stack(pivot: pd.DataFrame) -> list[str]:
        """Order techs so the legend matches what the eye sees on the stacked chart.

        Visual reading top-to-bottom:
        - Top of chart = top of positive stack = the LAST positive column (alphabetically),
          since pandas stacks col[0] just above zero and col[N-1] at the top.
        - Bottom of chart = bottom of negative stack = the LAST negative column (it draws
          below earlier negative columns, so the last column ends up furthest below zero).

        We split present techs into positive-total and negative-total groups, then build
        the top-to-bottom legend order: positives in reverse column order (largest-stacked
        at top) followed by negatives in original column order (closest-to-zero first,
        most-negative last).

        Args:
            pivot: Year-indexed frame, one column per technology, values in Mt CO2e.

        Returns:
            Tech names ordered top-to-bottom for direct use as legend handle order.
            Excludes techs whose values are all zero.
        """
        columns = list(pivot.columns)
        totals = pivot.sum(axis=0)
        present = [t for t in columns if (pivot[t] != 0).any()]
        positive = [t for t in present if totals[t] >= 0]
        negative = [t for t in present if totals[t] < 0]
        return list(reversed(positive)) + negative

    def _add_emissions_legends(self, ax, tech_handles: list, production_handles: list) -> None:
        """Render two separate legend boxes: technology (top) and production volume (bottom).

        Splitting them keeps the technology list dense and avoids visual ambiguity about
        which axis the production lines belong to. Production legend is omitted when no
        production overlay was drawn.

        Args:
            ax: Primary emissions axis.
            tech_handles: Patch handles for the technology legend, in display order
                (bottom-of-stack tech last).
            production_handles: Line2D proxies for iron/steel production overlays
                (may be empty).
        """
        if production_handles:
            tech_anchor = (1.15, 1.0)
            production_anchor = (1.15, 0.0)
            production_loc = "lower left"
        else:
            tech_anchor = self.config.legend_position
            production_anchor = None
            production_loc = self.config.legend_loc

        tech_legend = self._style_legend(
            ax,
            title="Technology emissions (left axis)",
            handles=tech_handles,
            labels=[h.get_label() for h in tech_handles],
            bbox_to_anchor=tech_anchor,
        )

        if production_handles and tech_legend is not None:
            ax.add_artist(tech_legend)  # keep tech legend visible when adding the second
            production_legend = ax.legend(
                handles=production_handles,
                labels=[h.get_label() for h in production_handles],
                title="Production volumes (right axis)",
                bbox_to_anchor=production_anchor,
                loc=production_loc,
                frameon=self.config.legend_frameon,
                fontsize=self.config.legend_fontsize,
            )
            if production_legend is not None:
                production_legend.get_title().set_fontweight("bold")

    @staticmethod
    def _plot_signed_stacked_area(
        ax,
        pivot: pd.DataFrame,
        colours: list,
        alpha: float = 0.8,
    ) -> None:
        """Stacked area plot tolerant of mixed-sign columns.

        Pandas' ``DataFrame.plot.area`` rejects columns containing both positive and
        negative values (e.g. charcoal+CCS credits flipping year-on-year), so we split
        each column into positive and negative halves via ``clip`` and stack them
        separately. Positives accumulate upward from zero, negatives downward.

        After both halves are drawn we explicitly set the y-axis range from the stack
        totals: pandas' second call would otherwise call ``set_ylim(None, 0)`` and
        clobber the upper bound established by the positive half.

        Args:
            ax: Matplotlib axes to draw on.
            pivot: Year-indexed frame, one column per technology.
            colours: One colour per column, in the same order as ``pivot.columns``.
            alpha: Fill alpha applied to both halves.
        """
        positive = pivot.clip(lower=0)
        negative = pivot.clip(upper=0)
        has_positive = bool((positive != 0).any().any())
        has_negative = bool((negative != 0).any().any())
        if has_positive:
            positive.plot.area(ax=ax, color=colours, alpha=alpha, linewidth=0, legend=False)
        if has_negative:
            negative.plot.area(ax=ax, color=colours, alpha=alpha, linewidth=0, legend=False)

        y_max = float(positive.sum(axis=1).max()) if has_positive else 0.0
        y_min = float(negative.sum(axis=1).min()) if has_negative else 0.0
        margin = max(abs(y_max), abs(y_min)) * 0.05 or 1.0
        ax.set_ylim(y_min - margin if has_negative else 0, y_max + margin)

    @staticmethod
    def _lighten_colour(colour, factor: float = 0.5) -> tuple[float, float, float]:
        """Blend ``colour`` with white by ``factor`` to produce a lighter shade.

        Args:
            colour: Any matplotlib-recognised colour spec (hex, name, RGB tuple).
            factor: Blend strength in [0, 1]. 0 returns the original colour, 1 returns white.

        Returns:
            (r, g, b) tuple in [0, 1].
        """
        r, g, b = mcolors.to_rgb(colour)
        return (r + (1 - r) * factor, g + (1 - g) * factor, b + (1 - b) * factor)

