# ============================================================================
# Configuration
# ============================================================================


@dataclass
class PlotConfig:
    """Configuration for consistent plot styling across all Steel-IQ visualizations.

    This class centralizes styling decisions for plots, making it easy to maintain
    consistency and customize appearance globally.

    Attributes:
        footer_template: Template string for plot footers. Use {date} and {version} placeholders.
        show_footer: Whether to display footer on plots
        legend_position: Legend position as (x, y) coordinates
        legend_loc: Legend location string (e.g., "upper left")
        legend_frameon: Whether to show frame around legend
        legend_fontsize: Font size for legend text
        default_dpi: Resolution for saved plots
        default_figsize_wide: Figure size for wide plots (width, height)
        default_figsize_square: Figure size for square plots (width, height)
        grid_alpha: Transparency of grid lines
        grid_linestyle: Style of grid lines
        tech_colors: Technology color mapping (will be copied from global tech2colours if not provided)
        region_colors: Region color mapping (will be copied from global region2colours if not provided)
    """

    footer_template: str = "Generated by Steel-IQ on {date}"
    show_footer: bool = True
    legend_position: tuple[float, float] = (1.05, 1)
    legend_loc: str = "upper left"
    legend_frameon: bool = True
    legend_fontsize: int = 10
    default_dpi: int = 300
    default_figsize_wide: tuple[int, int] = (12, 7)
    default_figsize_square: tuple[int, int] = (10, 10)
    grid_alpha: float = 0.3
    grid_linestyle: str = "--"
    tech_colors: dict[str, str] = field(default_factory=dict)
    region_colors: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        """Initialize color mappings from global defaults if not provided."""
        if not self.tech_colors:
            self.tech_colors = tech2colours.copy()
        if not self.region_colors:
            self.region_colors = region2colours.copy()


