    def plot_capex_by_technology(
        self,
        trace_capex: dict[int, dict[str, dict[str, float]]],
        iso3_filter: Optional[str] = None,
        export_csv: bool = True,
    ) -> Optional[Path]:
        """Plot total CAPEX investments by technology over years as a stacked bar chart.

        Args:
            trace_capex: Nested dict {year: {technology: {iso3: total_capex_usd}}}
            iso3_filter: Optional ISO3 country code to filter investments
            export_csv: If True, also export chart data to CSV (default: True)

        Returns:
            Path to saved plot, or None if no data to plot
        """
        if not trace_capex:
            self.logger.warning("No CAPEX data to plot")
            return None

        # Get full year range
        all_years = sorted(trace_capex.keys())
        if not all_years:
            return None

        year_min = min(all_years)
        year_max = max(all_years)
        full_year_range = list(range(year_min, year_max + 1))

        # Convert to DataFrame
        data_rows = []
        for year, techs in trace_capex.items():
            for tech, locations in techs.items():
                for iso3, capex in locations.items():
                    if iso3_filter is None or iso3 == iso3_filter:
                        data_rows.append({"year": year, "technology": tech, "iso3": iso3, "capex": capex})

        if not data_rows:
            self.logger.warning(f"No CAPEX data after filtering{f' for {iso3_filter}' if iso3_filter else ''}")
            return None

        df = pd.DataFrame(data_rows)
        df["capex_bn"] = df["capex"] / 1e9

        # Aggregate by year and technology
        capex_by_year_tech = df.groupby(["year", "technology"])["capex_bn"].sum().unstack("technology", fill_value=0)
        capex_by_year_tech = capex_by_year_tech.reindex(full_year_range, fill_value=0)

        # Ensure colors for all technologies
        for tech in capex_by_year_tech.columns:
            self._ensure_tech_color(tech)

        # Create plot
        fig, ax = plt.subplots(figsize=self.config.default_figsize_wide)

        capex_by_year_tech.plot.bar(
            stacked=True,
            ax=ax,
            color=[self.config.tech_colors.get(tech, "brown") for tech in capex_by_year_tech.columns],
            width=0.8,
        )

        # Formatting
        location_str = f" in {iso3_filter}" if iso3_filter else " (Global)"
        ax.set_title(f"CAPEX Investments by Technology{location_str}", fontsize=14, fontweight="bold")
        ax.set_xlabel("Year", fontsize=12)
        ax.set_ylabel("Total CAPEX (Billion USD)", fontsize=12)
        legend_techs = self._legend_order_for_stack(capex_by_year_tech)
        tech_handles = [
            Patch(facecolor=self.config.tech_colors.get(tech, "brown"), label=tech) for tech in legend_techs
        ]
        self._style_legend(ax, title="Technology", handles=tech_handles, labels=legend_techs)
        ax.grid(axis="y", alpha=self.config.grid_alpha, linestyle=self.config.grid_linestyle)

        # X-axis formatting
        ax.set_xticks(range(len(full_year_range)))
        ax.set_xticklabels([str(year) for year in full_year_range], rotation=45, ha="right")

        # Thin out labels if too many years
        if len(full_year_range) > 20:
            step = 5 if len(full_year_range) > 50 else 2
            for i, label in enumerate(ax.xaxis.get_ticklabels()):
                if i % step != 0:
                    label.set_visible(False)

        # Add value labels on significant bars
        for container in ax.containers:
            if isinstance(container, BarContainer):
                heights = [patch.get_height() for patch in container.patches]
                labels = [f"{float(h):.1f}" if float(h) > 0.1 else "" for h in heights]
                ax.bar_label(container, labels=labels, label_type="center", fontsize=8, color="white", weight="bold")

        # Ensure y-axis starts at 0
        self._ensure_y_axis_starts_at_zero(ax)

        fig.tight_layout()

        # Save
        filename = f"capex_by_technology_and_year{'_' + iso3_filter if iso3_filter else ''}.png"

        # Export CSV if requested
        if export_csv:
            self._save_chart_data_to_csv(capex_by_year_tech, filename)

        return self._save_figure(fig, filename)

    def plot_emissions_by_technology(
        self,
        trace_emissions: dict[str, dict[int, dict[str, dict[str, float]]]],
        trace_production_by_product: Optional[dict[int, dict[str, float]]] = None,
        export_csv: bool = True,
    ) -> list[Path]:
        """Plot per-scope emissions by technology over time as five stacked area charts per boundary.

        Direct (excl. biogenic) and direct-with-biomass are alternative accountings of
        the same direct emissions and must never be summed together. This method emits
        five chart variants per emissions boundary present in the trace:

        - ``emissions_direct_by_technology__<boundary>.png`` — direct only
        - ``emissions_direct_with_biomass_by_technology__<boundary>.png`` — direct including biogenic
        - ``emissions_indirect_by_technology__<boundary>.png`` — indirect only
        - ``emissions_direct_plus_indirect_by_technology__<boundary>.png`` — direct on bottom, indirect (lighter) on top
        - ``emissions_direct_with_biomass_plus_indirect_by_technology__<boundary>.png`` — same with biogenic direct

        Args:
            trace_emissions: Nested dict {boundary: {year: {technology: {scope: emissions_tCO2e}}}},
                where scope is one of ``direct_ghg``, ``direct_with_biomass_ghg``,
                ``indirect_ghg``.
            trace_production_by_product: Optional {year: {"iron"/"steel": tonnes}}. When provided,
                each chart overlays iron and steel production as lines on a secondary axis.
            export_csv: If True, also export each chart's underlying data to CSV.

        Returns:
            List of paths to the saved plots (empty if there was nothing to plot).
        """
        if not trace_emissions:
            self.logger.warning("No emissions data to plot")
            return []

        production_df: Optional[pd.DataFrame] = None
        if trace_production_by_product:
            prod_rows = [
                {"year": year, "product": product, "production_mt": tonnes / 1e6}
                for year, by_product in trace_production_by_product.items()
                for product, tonnes in by_product.items()
            ]
            if prod_rows:
                production_df = (
                    pd.DataFrame(prod_rows).pivot(index="year", columns="product", values="production_mt").fillna(0.0)
                )

        saved: list[Path] = []
        for boundary, by_year in trace_emissions.items():
            saved.extend(
                self._plot_emissions_for_boundary(
                    boundary=boundary,
                    by_year=by_year,
                    production_df=production_df,
                    export_csv=export_csv,
                )
            )
        return saved

    def _plot_emissions_for_boundary(
        self,
        boundary: str,
        by_year: dict[int, dict[str, dict[str, float]]],
        production_df: Optional[pd.DataFrame],
        export_csv: bool,
    ) -> list[Path]:
        """Render the five emissions chart variants for a single boundary."""
        rows = []
        for year, by_tech in by_year.items():
            for tech, by_scope in by_tech.items():
                rows.append(
                    {
                        "year": year,
                        "technology": tech,
                        "direct_ghg": by_scope.get("direct_ghg", 0.0),
                        "direct_with_biomass_ghg": by_scope.get("direct_with_biomass_ghg", 0.0),
                        "indirect_ghg": by_scope.get("indirect_ghg", 0.0),
                    }
                )
        if not rows:
            return []

        df = pd.DataFrame(rows)
        for col in ("direct_ghg", "direct_with_biomass_ghg", "indirect_ghg"):
            df[col] = df[col] / 1e6  # tCO2e -> Mt CO2e

        direct_pivot = df.pivot(index="year", columns="technology", values="direct_ghg").fillna(0)
        direct_bio_pivot = df.pivot(index="year", columns="technology", values="direct_with_biomass_ghg").fillna(0)
        indirect_pivot = df.pivot(index="year", columns="technology", values="indirect_ghg").fillna(0)

        for tech in direct_pivot.columns:
            self._ensure_tech_color(tech)

        subtitle = f"Emissions boundary: {boundary.replace('_', ' ')}"
        suffix = boundary  # already snake_case; safe filename
        subdir = self.EMISSIONS_SUBDIR

        saved: list[Path] = []
        single_charts = [
            (
                "Direct emissions (excl. biogenic) by Technology",
                direct_pivot,
                f"{subdir}/emissions_direct_by_technology__{suffix}.png",
            ),
            (
                "Direct emissions (incl. biogenic) by Technology",
                direct_bio_pivot,
                f"{subdir}/emissions_direct_with_biomass_by_technology__{suffix}.png",
            ),
            (
                "Indirect emissions by Technology",
                indirect_pivot,
                f"{subdir}/emissions_indirect_by_technology__{suffix}.png",
            ),
        ]
        for title, pivot, filename in single_charts:
            path = self._plot_single_scope_emissions(
                pivot,
                title=title,
                subtitle=subtitle,
                filename=filename,
                export_csv=export_csv,
                production_df=production_df,
            )
            if path is not None:
                saved.append(path)

        combined_charts = [
            (
                "Direct (excl. biogenic) + Indirect emissions by Technology",
                direct_pivot,
                indirect_pivot,
                f"{subdir}/emissions_direct_plus_indirect_by_technology__{suffix}.png",
            ),
            (
                "Direct (incl. biogenic) + Indirect emissions by Technology",
                direct_bio_pivot,
                indirect_pivot,
                f"{subdir}/emissions_direct_with_biomass_plus_indirect_by_technology__{suffix}.png",
            ),
        ]
        for title, direct_part, indirect_part, filename in combined_charts:
            path = self._plot_combined_scope_emissions(
                direct_part,
                indirect_part,
                title=title,
                subtitle=subtitle,
                filename=filename,
                export_csv=export_csv,
                production_df=production_df,
            )
            if path is not None:
                saved.append(path)

        return saved

    def _plot_single_scope_emissions(
        self,
        pivot: pd.DataFrame,
        title: str,
        subtitle: str,
        filename: str,
        export_csv: bool,
        production_df: Optional[pd.DataFrame] = None,
    ) -> Optional[Path]:
        """Render one stacked-area chart for a single emissions scope.

        Args:
            pivot: DataFrame indexed by year, technologies as columns, values in Mt CO2e.
            title: Chart title.
            subtitle: Subtitle (typically the emissions boundary).
            filename: Output PNG filename (CSV uses the same stem).
            export_csv: If True, also write the pivot to CSV alongside the PNG.
            production_df: Optional iron/steel production overlay (Mt) keyed by year.

        Returns:
            Path to the saved figure, or None if there is nothing to plot.
        """
        if pivot.empty:
            return None

        fig, ax = plt.subplots(figsize=self.config.default_figsize_wide)
        colours = [self.config.tech_colors.get(tech, "brown") for tech in pivot.columns]
        self._plot_signed_stacked_area(ax, pivot, colours, alpha=0.8)
        production_handles = self._overlay_production_lines(ax, production_df)
        self._finalise_emissions_axes(ax, pivot.index, title=title, subtitle=subtitle)

        legend_techs = self._legend_order_for_stack(pivot)
        tech_handles = [
            Patch(facecolor=self.config.tech_colors.get(tech, "brown"), label=tech) for tech in legend_techs
        ]
        self._add_emissions_legends(ax, tech_handles, production_handles)
        fig.tight_layout()

        if export_csv:
            self._save_chart_data_to_csv(pivot, filename, subdir="plots_dir")
        return self._save_figure(fig, filename, subdir="plots_dir")

    def _plot_combined_scope_emissions(
        self,
        direct: pd.DataFrame,
        indirect: pd.DataFrame,
        title: str,
        subtitle: str,
        filename: str,
        export_csv: bool,
        production_df: Optional[pd.DataFrame] = None,
    ) -> Optional[Path]:
        """Render a stacked-area chart with direct on the bottom and indirect (lighter) on top per tech.

        The two pivots are joined column-wise into a single DataFrame whose columns
        alternate (direct, indirect) per technology so that matplotlib's area stack
        places the indirect band immediately above its corresponding direct band.

        Args:
            direct: Per-tech direct emissions (Mt CO2e), indexed by year.
            indirect: Per-tech indirect emissions (Mt CO2e), indexed by year. Must share columns/index with ``direct``.
            title: Chart title.
            subtitle: Subtitle (typically the emissions boundary).
            filename: Output PNG filename.
            export_csv: If True, also export the combined data.

        Returns:
            Path to the saved figure, or None if both inputs are empty.
        """
        if direct.empty and indirect.empty:
            return None

        techs = list(direct.columns.union(indirect.columns))
        years = direct.index.union(indirect.index)
        direct = direct.reindex(index=years, columns=techs).fillna(0)
        indirect = indirect.reindex(index=years, columns=techs).fillna(0)

        combined = pd.DataFrame(index=years)
        colours: list[Any] = []
        for tech in techs:
            base = self.config.tech_colors.get(tech, "brown")
            light = self._lighten_colour(base, factor=0.2)
            combined[f"{tech} (direct)"] = direct[tech]
            colours.append(base)
            combined[f"{tech} (indirect)"] = indirect[tech]
            colours.append(light)

        fig, ax = plt.subplots(figsize=self.config.default_figsize_wide)
        self._plot_signed_stacked_area(ax, combined, colours, alpha=0.85)
        production_handles = self._overlay_production_lines(ax, production_df)

        # Order by direct + indirect so techs visible only via their indirect band
        # (e.g. BOF, which has zero direct in responsible_steel) still appear in the legend.
        legend_techs = self._legend_order_for_stack(direct + indirect)
        tech_handles = [
            Patch(facecolor=self.config.tech_colors.get(tech, "brown"), label=tech) for tech in legend_techs
        ]
        tech_handles.append(Patch(facecolor="lightgrey", label="lighter shade = indirect"))

        self._finalise_emissions_axes(ax, years, title=title, subtitle=subtitle)
        self._add_emissions_legends(ax, tech_handles, production_handles)
        fig.tight_layout()

        if export_csv:
            self._save_chart_data_to_csv(combined, filename, subdir="plots_dir")
        return self._save_figure(fig, filename, subdir="plots_dir")

