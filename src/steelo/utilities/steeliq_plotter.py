class SteelPlotter:
    """Main plotting class for Steel-IQ visualizations.

    This class provides a consistent interface for all Steel-IQ plots with
    centralized styling, footer management, and color scheme handling.

    Class attributes:
        EMISSIONS_SUBDIR: Subdirectory under ``plots_dir`` (sibling to PAM/GEO/TM)
            where emission charts are written. Kept centralised so call sites and
            tests reference one symbol.

    Example:
        >>> config = PlotConfig(footer_template="Generated by Steel-IQ v2.0 on {date}")
        >>> plotter = SteelPlotter(config, plot_paths)
        >>> plotter.plot_capex_by_technology(data_collector.trace_capex)
        >>> plotter.plot_emissions_by_technology(data_collector.trace_emissions)
    """

    EMISSIONS_SUBDIR = "emissions"
    COST_CURVES_SUBDIR = "cost_curves"

    def __init__(self, config: Optional[PlotConfig] = None, plot_paths: Optional["PlotPaths"] = None):
        """Initialize the SteelIQ plotter.

        Args:
            config: Plot configuration. If None, uses default PlotConfig.
            plot_paths: Output paths for saving plots. Required for saving plots.
        """
        self.config = config or PlotConfig()
        self.plot_paths = plot_paths
        self.logger = logging.getLogger(f"{__name__}.SteelPlotter")

    # ========================================================================
    # Helper Methods
    # ========================================================================

    def _apply_footer(self, fig: Figure) -> None:
        """Apply consistent footer to a figure.

        Args:
            fig: Matplotlib figure to add footer to
        """
        if not self.config.show_footer:
            return

        footer_text = self.config.footer_template.format(
            date=datetime.now().strftime("%Y-%m-%d"),
            version="1.0",  # TODO: Get from package version
        )

        fig.text(
            0.99,
            0.01,
            footer_text,
            ha="right",
            va="bottom",
            fontsize=8,
            color="gray",
            style="italic",
        )

    def _style_legend(self, ax, title: str = "", handles=None, labels=None, bbox_to_anchor=None):
        """Apply consistent legend styling to an axes.

        Args:
            ax: Matplotlib axes to style legend for
            title: Legend title
            handles: Optional custom legend handles
            labels: Optional custom legend labels
            bbox_to_anchor: Optional override for legend anchor; defaults to ``self.config.legend_position``.

        Returns:
            The Legend artist created (or None if no legend was produced).
        """
        anchor = bbox_to_anchor if bbox_to_anchor is not None else self.config.legend_position
        if handles is not None and labels is not None:
            legend = ax.legend(
                handles=handles,
                labels=labels,
                title=title,
                bbox_to_anchor=anchor,
                loc=self.config.legend_loc,
                frameon=self.config.legend_frameon,
                fontsize=self.config.legend_fontsize,
            )
        else:
            legend = ax.legend(
                title=title,
                bbox_to_anchor=anchor,
                loc=self.config.legend_loc,
                frameon=self.config.legend_frameon,
                fontsize=self.config.legend_fontsize,
            )
        if legend and title:
            legend.get_title().set_fontweight("bold")
        return legend

    def _save_figure(self, fig: Figure, filename: str, subdir: str = "pam_plots_dir") -> Path:
        """Save figure with consistent settings.

        Args:
            fig: Figure to save
            filename: Output filename
            subdir: Subdirectory attribute name from PlotPaths ("pam_plots_dir", "geo_plots_dir", etc.)

        Returns:
            Path where figure was saved

        Raises:
            ValueError: If plot_paths not set or subdirectory not found
        """
        if self.plot_paths is None:
            raise ValueError("plot_paths must be set to save figures")

        plot_dir = getattr(self.plot_paths, subdir, None)
        if plot_dir is None:
            raise ValueError(f"PlotPaths does not have attribute '{subdir}'")

        output_path = plot_dir / filename
        output_path.parent.mkdir(parents=True, exist_ok=True)

        self._apply_footer(fig)
        fig.savefig(output_path, dpi=self.config.default_dpi, bbox_inches="tight")
        plt.close(fig)

        self.logger.info(f"Saved plot to {output_path}")
        return output_path

    def _ensure_tech_color(self, tech: str) -> str:
        """Get color for technology, assigning default if not found.

        Args:
            tech: Technology name

        Returns:
            Color code for the technology
        """
        if tech not in self.config.tech_colors:
            self.config.tech_colors[tech] = "brown"
            self.logger.warning(f"No color defined for technology '{tech}', using brown")
        return self.config.tech_colors[tech]

    def _get_iron_ore_quality_color(self, quality: str) -> str:
        """Get color for iron ore quality, with fallback logic.

        Args:
            quality: Iron ore quality name

        Returns:
            Color code for the quality
        """
        quality_lower = quality.lower()
        # Try to match against known quality keys
        for key, color in self.config.iron_ore_quality_colors.items():
            if key in quality_lower:
                return color
        # Fallback to gray if not found
        self.logger.warning(f"No color defined for iron ore quality '{quality}', using gray")
        return "#808080"

    def _get_metallic_charge_color(self, charge_type: str) -> str:
        """Get color for metallic charge type, with fallback logic.

        Args:
            charge_type: Metallic charge type name

        Returns:
            Color code for the charge type
        """
        charge_lower = charge_type.lower()
        # Try to match against known charge type keys
        for key, color in self.config.metallic_charge_colors.items():
            if key in charge_lower:
                return color
        # Fallback: assign a consistent color based on hash
        if charge_lower not in self.config.metallic_charge_colors:
            # Use thematically consistent colors for unknown charge types
            # (grays, blues, and earth tones to match existing scheme)
            color_palette = [
                "#5F9EA0",  # cadet blue
                "#778899",  # light slate gray
                "#BC8F8F",  # rosy brown
                "#4169E1",  # royal blue
                "#A9A9A9",  # dark gray
                "#8FBC8F",  # dark sea green
            ]
            color = color_palette[hash(charge_lower) % len(color_palette)]
            self.config.metallic_charge_colors[charge_lower] = color
            self.logger.info(f"Assigned color {color} to metallic charge '{charge_type}'")
        return self.config.metallic_charge_colors[charge_lower]

    def _save_chart_data_to_csv(self, df: pd.DataFrame, filename: str, subdir: str = "pam_plots_dir") -> Optional[Path]:
        """Save chart data to CSV file.

        Args:
            df: DataFrame containing the chart data
            filename: Output filename (will replace .png with .csv)
            subdir: Subdirectory attribute name from PlotPaths

        Returns:
            Path where CSV was saved, or None if plot_paths not set
        """
        if self.plot_paths is None:
            self.logger.warning("plot_paths not set, skipping CSV export")
            return None

        plot_dir = getattr(self.plot_paths, subdir, None)
        if plot_dir is None:
            self.logger.warning(f"PlotPaths does not have attribute '{subdir}', skipping CSV export")
            return None

        # Replace .png extension with .csv
        csv_filename = filename.replace(".png", ".csv")
        output_path = plot_dir / csv_filename
        output_path.parent.mkdir(parents=True, exist_ok=True)

        try:
            df.to_csv(output_path, index=True)
            self.logger.info(f"Saved chart data to {output_path}")
            return output_path
        except Exception as e:
            self.logger.error(f"Failed to save CSV to {output_path}: {e}")
            return None

    def _ensure_y_axis_starts_at_zero(self, ax, upper_margin: float = 1.1):
        """Ensure y-axis starts at 0 and has appropriate upper limit.

        Args:
            ax: Matplotlib axis object
            upper_margin: Factor to multiply max value for upper limit (default: 1.1 = 10% margin)
        """
        current_ylim = ax.get_ylim()
        # Set lower limit to 0
        # For upper limit, use current max or add margin
        if current_ylim[1] > 0:
            ax.set_ylim(0, current_ylim[1] * upper_margin)
        else:
            # If no positive data, just set a reasonable range
            ax.set_ylim(0, 1)

